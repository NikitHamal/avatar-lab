import { execFileSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { pathToFileURL, fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))

const loadTypeScript = async () => {
  try {
    return await import('typescript')
  } catch {
    const globalRoot = execFileSync('npm', ['root', '-g'], { encoding: 'utf8' }).trim()
    return import(pathToFileURL(path.join(globalRoot, 'typescript/lib/typescript.js')).href)
  }
}

const fallbackBundle = async () => {
  const tsModule = await loadTypeScript()
  const ts = tsModule.default ?? tsModule
  const sources = {
    '/avatar/surfaces': 'src/features/avatar/surfaces.ts',
    '/avatar/geometry': 'src/features/avatar/geometry.ts',
    '/creature/creatureExpression': 'src/features/creature/creatureExpression.ts',
    '/avatar/ambientMotion': 'src/features/avatar/ambientMotion.ts',
    '/export/standaloneEngine.entry': 'src/features/export/standaloneEngine.entry.ts',
  }
  const compiled = {}
  for (const [id, relativePath] of Object.entries(sources)) {
    const source = await readFile(path.join(root, relativePath), 'utf8')
    compiled[id] = ts.transpileModule(source, {
      compilerOptions: {
        target: ts.ScriptTarget.ES2020,
        module: ts.ModuleKind.CommonJS,
        esModuleInterop: true,
        removeComments: true,
      },
      fileName: relativePath,
    }).outputText
  }

  const moduleTable = Object.entries(compiled)
    .map(([id, code]) => `${JSON.stringify(id)}:function(require,module,exports){${code}}`)
    .join(',')
  return `var AvatarProceduralEngine=(function(){var modules={${moduleTable}},cache={};function resolve(from,request){if(request[0]!=='.')return request;var parts=from.split('/');parts.pop();request.split('/').forEach(function(part){if(!part||part==='.')return;if(part==='..')parts.pop();else parts.push(part)});return parts.join('/')||'/'}function load(id){if(cache[id])return cache[id].exports;var factory=modules[id];if(!factory)throw new Error('Standalone module not found: '+id);var module={exports:{}};cache[id]=module;factory(function(request){return load(resolve(id,request))},module,module.exports);return module.exports}return load('/export/standaloneEngine.entry')})();`
}

const viteBundle = async build => {
  const result = await build({
    configFile: false,
    logLevel: 'silent',
    build: {
      write: false,
      minify: true,
      lib: {
        entry: path.join(root, 'src/features/export/standaloneEngine.entry.ts'),
        formats: ['iife'],
        name: 'AvatarProceduralEngine',
      },
    },
  })
  const outputs = Array.isArray(result) ? result.flatMap(item => item.output) : result.output
  const chunk = outputs.find(item => item.type === 'chunk')
  if (!chunk) throw new Error('Standalone avatar engine bundle was not generated.')
  return chunk.code
}

let code
let viteBuild
try {
  const vite = await import('vite')
  viteBuild = vite.build
} catch (error) {
  if (process.env.AVATAR_LAB_ENGINE_STRICT === '1') throw error
}

if (viteBuild) {
  // If Vite is installed, build failures must remain visible instead of being hidden by the fallback.
  code = await viteBundle(viteBuild)
} else {
  console.warn('Vite is unavailable; using the TypeScript fallback standalone bundler.')
  code = await fallbackBundle()
}

const outputPath = path.join(root, 'src/features/export/standaloneEngine.generated.ts')
const source = `// Generated by scripts/generate-standalone-engine.mjs. Do not edit.\nexport const standaloneEngineSource = ${JSON.stringify(code)}\n`

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  if (current !== source) throw new Error('Standalone avatar engine is stale. Run pnpm engine.')
} else {
  await writeFile(outputPath, source)
}
